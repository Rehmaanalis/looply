import { ProjectData, AssetRecord } from '@/types/animation';

export interface CSSExportOptions {
  mode: 'zip' | 'inline' | 'external';
  assetPathPrefix?: string; // e.g., 'assets/' or 'https://cdn.example.com/'
}

export interface ExportCompatibilityReport {
  fullySupported: string[];
  sampledPhysics: string[];
  warnings: string[];
}

export interface GeneratedCSSResult {
  css: string;
  html: string;
  stageHtml: string;
  readme: string;
  report: ExportCompatibilityReport;
}

export function sanitizeCssIdentifier(str: string): string {
  return str.replace(/[^a-zA-Z0-9_-]/g, '_').toLowerCase();
}

/**
 * Ensures data URLs are safely encoded for HTML attributes and CSS embedding.
 * Converts raw XML SVG data URLs to safe base64 to prevent broken HTML attributes.
 */
export function ensureSafeDataUrl(url: string | undefined): string {
  if (!url) return '';
  if (url.startsWith('data:image/svg+xml') && !url.includes(';base64,')) {
    const commaIndex = url.indexOf(',');
    if (commaIndex !== -1) {
      const rawContent = url.slice(commaIndex + 1);
      try {
        const decoded = rawContent.startsWith('%') ? decodeURIComponent(rawContent) : rawContent;
        if (typeof window !== 'undefined' && typeof window.btoa === 'function') {
          return `data:image/svg+xml;base64,${window.btoa(unescape(encodeURIComponent(decoded)))}`;
        } else if (typeof Buffer !== 'undefined') {
          return `data:image/svg+xml;base64,${Buffer.from(decoded, 'utf-8').toString('base64')}`;
        }
      } catch {
        return url.replace(/"/g, '&quot;');
      }
    }
  }
  return url;
}

/**
 * Returns a consistent, unique, deterministic filename for an asset to prevent
 * name collisions in ZIP exports and HTML/CSS references.
 */
export function getAssetFilename(asset: AssetRecord | undefined, fallbackIndex: number = 0): string {
  if (!asset) return `asset_${fallbackIndex + 1}.png`;
  const ext = asset.type?.includes('svg')
    ? 'svg'
    : asset.type?.includes('jpeg') || asset.type?.includes('jpg')
    ? 'jpg'
    : asset.type?.includes('webp')
    ? 'webp'
    : 'png';
  const rawName = asset.name ? asset.name.replace(/\.[^/.]+$/, '') : `asset_${fallbackIndex + 1}`;
  const cleanName = sanitizeCssIdentifier(rawName);
  const idSuffix = asset.id ? asset.id.replace(/[^a-zA-Z0-9]/g, '').slice(-6) : `${fallbackIndex + 1}`;
  return `${cleanName}_${idSuffix}.${ext}`;
}

export function generateAnimationCSS(project: ProjectData, options: CSSExportOptions): GeneratedCSSResult {
  const { width, height, background, duration, loop, direction } = project.settings;
  const totalDuration = Math.max(0.1, duration || 3);
  const iterationCount = loop ? 'infinite' : '1';
  const animDirection = direction || 'normal';

  const report: ExportCompatibilityReport = {
    fullySupported: [
      'W3C CSS3 GPU-accelerated Transforms (translate3d, scale, rotate)',
      'Master timeline multi-layer synchronization',
      'Per-keyframe cubic-bezier and standard timing functions',
      'Timeline in-point and out-point active span clipping',
      'Individual layer transform-origins (X/Y %)',
    ],
    sampledPhysics: [],
    warnings: [],
  };

  let cssOutput = `/* ========================================================\n`;
  cssOutput += `   Generated by Looply Studio - Local-First Visual Animation\n`;
  cssOutput += `   Project: ${project.name}\n`;
  cssOutput += `   Duration: ${totalDuration}s | Stage: ${width}x${height}px | Layers: ${project.layers.length}\n`;
  cssOutput += `   ======================================================== */\n\n`;

  // Stage CSS
  cssOutput += `.looply-stage {\n`;
  cssOutput += `  position: relative;\n`;
  cssOutput += `  width: ${width}px;\n`;
  cssOutput += `  height: ${height}px;\n`;
  cssOutput += `  background-color: ${background || '#0f1117'};\n`;
  cssOutput += `  overflow: hidden;\n`;
  cssOutput += `  margin: 0 auto;\n`;
  cssOutput += `  box-sizing: border-box;\n`;
  cssOutput += `}\n\n`;

  // Base Layer CSS
  cssOutput += `.looply-layer {\n`;
  cssOutput += `  position: absolute;\n`;
  cssOutput += `  top: 0;\n`;
  cssOutput += `  left: 0;\n`;
  cssOutput += `  pointer-events: none;\n`;
  cssOutput += `  user-select: none;\n`;
  cssOutput += `  will-change: transform, opacity;\n`;
  cssOutput += `}\n\n`;

  let htmlLayers = '';

  // Sort layers by z-index for correct stacking order in DOM
  const sortedLayers = [...project.layers].sort((a, b) => a.zIndex - b.zIndex);
  const assetKeys = Object.keys(project.assets);

  sortedLayers.forEach((layer, index) => {
    const layerClass = `looply-layer-${sanitizeCssIdentifier(layer.id)}`;
    const animName = `looply-anim-${sanitizeCssIdentifier(layer.id)}`;
    const asset = project.assets[layer.assetId];

    // Determine asset src based on options
    let assetSrc = '';
    if (options.mode === 'inline') {
      assetSrc = ensureSafeDataUrl(asset?.dataUrl) || '';
    } else {
      const prefix = options.mode === 'zip' ? 'assets/' : (options.assetPathPrefix || 'assets/');
      const assetIndex = assetKeys.indexOf(layer.assetId);
      const filename = getAssetFilename(asset, assetIndex >= 0 ? assetIndex : index);
      assetSrc = `${prefix}${filename}`;
    }

    htmlLayers += `    <div class="looply-layer ${layerClass}">\n`;
    htmlLayers += `      <img src="${assetSrc}" alt="${layer.name}" width="${layer.width}" height="${layer.height}" loading="eager" />\n`;
    htmlLayers += `    </div>\n`;

    // Timeline in/out boundaries
    const startSec = Math.max(0, layer.startTime ?? 0);
    const endSec = Math.min(totalDuration, layer.endTime !== undefined ? layer.endTime : totalDuration);
    const hasTimingClip = startSec > 0.02 || endSec < totalDuration - 0.02;

    const keyframes = layer.keyframes ? [...layer.keyframes].sort((a, b) => a.time - b.time) : [];
    const hasKeyframes = keyframes.length > 0;
    const hasSpring =
      layer.easing === 'spring' ||
      !!layer.springConfig ||
      keyframes.some((k) => k.easing === 'spring' || !!k.springConfig);

    if (hasSpring) {
      report.sampledPhysics.push(`Layer "${layer.name}": Physical spring dynamics sampled to native CSS keyframes.`);
    }

    cssOutput += `/* Layer: ${layer.name} */\n`;
    cssOutput += `.${layerClass} {\n`;
    cssOutput += `  width: ${layer.width}px;\n`;
    cssOutput += `  height: ${layer.height}px;\n`;
    cssOutput += `  z-index: ${layer.zIndex || index + 1};\n`;
    cssOutput += `  transform-origin: ${layer.originX}% ${layer.originY}%;\n`;

    const needsAnimation = hasKeyframes || hasTimingClip;

    if (needsAnimation) {
      // Synchronize layer animation to master project timeline duration
      // Individual keyframes specify their own animation-timing-function for multi-segment curves
      cssOutput += `  animation: ${animName} ${totalDuration}s linear 0s ${iterationCount} ${animDirection} both;\n`;
    } else {
      // Static transform
      cssOutput += `  transform: translate3d(${layer.x}px, ${layer.y}px, 0) rotate(${layer.rotation}deg) scale(${layer.scaleX}, ${layer.scaleY});\n`;
      cssOutput += `  opacity: ${layer.opacity};\n`;
      report.warnings.push(`Layer "${layer.name}" is static and runs without motion keyframes.`);
    }

    cssOutput += `}\n\n`;

    // Layer image element styling
    cssOutput += `.${layerClass} img {\n`;
    cssOutput += `  width: 100%;\n`;
    cssOutput += `  height: 100%;\n`;
    cssOutput += `  display: block;\n`;
    cssOutput += `  object-fit: contain;\n`;
    cssOutput += `}\n\n`;

    // Generate @keyframes locked to master project duration
    if (needsAnimation) {
      cssOutput += `@keyframes ${animName} {\n`;

      if (hasKeyframes) {
        // If layer active span starts after 0s, insert 0% hidden state
        if (startSec > 0.02) {
          const firstKf = keyframes[0];
          const px = firstKf.properties.x ?? layer.x;
          const py = firstKf.properties.y ?? layer.y;
          const rot = firstKf.properties.rotation ?? layer.rotation;
          const sx = firstKf.properties.scaleX ?? layer.scaleX;
          const sy = firstKf.properties.scaleY ?? layer.scaleY;

          cssOutput += `  0% {\n`;
          cssOutput += `    transform: translate3d(${px}px, ${py}px, 0) rotate(${rot}deg) scale(${sx}, ${sy});\n`;
          cssOutput += `    opacity: 0;\n`;
          cssOutput += `  }\n`;

          const preStartPct = Math.max(0, Math.round(((startSec - 0.01) / totalDuration) * 1000) / 10);
          cssOutput += `  ${preStartPct}% {\n`;
          cssOutput += `    opacity: 0;\n`;
          cssOutput += `  }\n`;
        }

        keyframes.forEach((kf, kfIdx) => {
          // Clamp keyframe time to project duration
          const kfTime = Math.max(0, Math.min(totalDuration, kf.time));
          const pct = Math.round((kfTime / totalDuration) * 1000) / 10;

          // Check if keyframe falls outside layer trimmed window
          const isBeforeInPoint = kfTime < startSec - 0.02;
          const isAfterOutPoint = kfTime > endSec + 0.02;

          const px = kf.properties.x ?? layer.x;
          const py = kf.properties.y ?? layer.y;
          const rot = kf.properties.rotation ?? layer.rotation;
          const sx = kf.properties.scaleX ?? layer.scaleX;
          const sy = kf.properties.scaleY ?? layer.scaleY;
          let op = kf.properties.opacity ?? layer.opacity;

          if (isBeforeInPoint || isAfterOutPoint) {
            op = 0;
          }

          // Specific easing for this keyframe segment
          const segmentEasing = kf.easing || layer.easing || 'ease';
          const validEasing = segmentEasing !== 'spring' ? segmentEasing : 'cubic-bezier(0.25, 1, 0.5, 1)';

          cssOutput += `  ${pct}% {\n`;
          cssOutput += `    transform: translate3d(${px}px, ${py}px, 0) rotate(${rot}deg) scale(${sx}, ${sy});\n`;
          cssOutput += `    opacity: ${op};\n`;
          if (kfIdx < keyframes.length - 1 && validEasing) {
            cssOutput += `    animation-timing-function: ${validEasing};\n`;
          }
          cssOutput += `  }\n`;
        });

        // Ensure 100% keyframe is always explicitly defined for smooth cycling
        const has100Pct = keyframes.some((k) => Math.abs(k.time - totalDuration) < 0.01);
        if (!has100Pct) {
          const lastKf = keyframes[keyframes.length - 1];
          const px = lastKf.properties.x ?? layer.x;
          const py = lastKf.properties.y ?? layer.y;
          const rot = lastKf.properties.rotation ?? layer.rotation;
          const sx = lastKf.properties.scaleX ?? layer.scaleX;
          const sy = lastKf.properties.scaleY ?? layer.scaleY;
          const op = endSec < totalDuration - 0.02 ? 0 : (lastKf.properties.opacity ?? layer.opacity);

          if (endSec < totalDuration - 0.02) {
            const postEndPct = Math.min(100, Math.round(((endSec + 0.01) / totalDuration) * 1000) / 10);
            cssOutput += `  ${postEndPct}% {\n`;
            cssOutput += `    opacity: 0;\n`;
            cssOutput += `  }\n`;
          }

          cssOutput += `  100% {\n`;
          cssOutput += `    transform: translate3d(${px}px, ${py}px, 0) rotate(${rot}deg) scale(${sx}, ${sy});\n`;
          cssOutput += `    opacity: ${op};\n`;
          cssOutput += `  }\n`;
        }
      } else if (hasTimingClip) {
        // Layer has no motion keyframes, but is trimmed on the timeline
        const px = layer.x;
        const py = layer.y;
        const rot = layer.rotation;
        const sx = layer.scaleX;
        const sy = layer.scaleY;
        const op = layer.opacity;

        if (startSec > 0.02) {
          cssOutput += `  0% {\n`;
          cssOutput += `    transform: translate3d(${px}px, ${py}px, 0) rotate(${rot}deg) scale(${sx}, ${sy});\n`;
          cssOutput += `    opacity: 0;\n`;
          cssOutput += `  }\n`;
          const preStartPct = Math.max(0, Math.round(((startSec - 0.01) / totalDuration) * 1000) / 10);
          cssOutput += `  ${preStartPct}% {\n    opacity: 0;\n  }\n`;
        }

        const startPct = Math.round((startSec / totalDuration) * 1000) / 10;
        cssOutput += `  ${startPct}% {\n`;
        cssOutput += `    transform: translate3d(${px}px, ${py}px, 0) rotate(${rot}deg) scale(${sx}, ${sy});\n`;
        cssOutput += `    opacity: ${op};\n`;
        cssOutput += `  }\n`;

        const endPct = Math.round((endSec / totalDuration) * 1000) / 10;
        cssOutput += `  ${endPct}% {\n`;
        cssOutput += `    transform: translate3d(${px}px, ${py}px, 0) rotate(${rot}deg) scale(${sx}, ${sy});\n`;
        cssOutput += `    opacity: ${op};\n`;
        cssOutput += `  }\n`;

        if (endSec < totalDuration - 0.02) {
          const postEndPct = Math.min(100, Math.round(((endSec + 0.01) / totalDuration) * 1000) / 10);
          cssOutput += `  ${postEndPct}% {\n    opacity: 0;\n  }\n`;
          cssOutput += `  100% {\n`;
          cssOutput += `    transform: translate3d(${px}px, ${py}px, 0) rotate(${rot}deg) scale(${sx}, ${sy});\n`;
          cssOutput += `    opacity: 0;\n`;
          cssOutput += `  }\n`;
        } else {
          cssOutput += `  100% {\n`;
          cssOutput += `    transform: translate3d(${px}px, ${py}px, 0) rotate(${rot}deg) scale(${sx}, ${sy});\n`;
          cssOutput += `    opacity: ${op};\n`;
          cssOutput += `  }\n`;
        }
      }

      cssOutput += `}\n\n`;
    }
  });

  const stageHtml = `<div class="looply-stage">\n${htmlLayers}</div>`;

  const html = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${project.name} - Looply Animation</title>
  <link rel="stylesheet" href="animation.css">
  <style>
    body {
      margin: 0;
      padding: 40px 20px;
      background: #090a0f;
      display: flex;
      flex-direction: column;
      align-items: center;
      justify-content: center;
      min-height: 100vh;
      font-family: system-ui, -apple-system, sans-serif;
      color: #f1f5f9;
    }
    .header {
      margin-bottom: 24px;
      text-align: center;
    }
    .header h1 {
      margin: 0 0 8px 0;
      font-size: 20px;
      font-weight: 600;
    }
    .header p {
      margin: 0;
      font-size: 14px;
      color: #94a3b8;
    }
    .wrapper {
      box-shadow: 0 25px 50px -12px rgba(0, 0, 0, 0.5), 0 0 0 1px rgba(255, 255, 255, 0.1);
      border-radius: 12px;
      overflow: hidden;
    }
  </style>
</head>
<body>
  <div class="header">
    <h1>${project.name}</h1>
    <p>Exported from Looply Studio (${totalDuration}s duration, ${project.layers.length} layers)</p>
  </div>
  <div class="wrapper">
${stageHtml}  </div>
</body>
</html>`;

  const readme = `# ${project.name} — Looply Animation Package

This package was exported from **Looply Visual Animation Studio**.
It runs entirely on standard CSS keyframe animations and HTML with zero runtime JavaScript dependencies.

## Structure
- \`index.html\`: Ready-to-view demo running the animation in a centered showcase.
- \`animation.css\`: The complete stylesheet with GPU-accelerated \`@keyframes\` and stage definitions.
- \`assets/\`: Image assets utilized across the animation layers.

## Master Timeline Synchronization
All layers are precisely synchronized to the master timeline duration of **${totalDuration}s**.
Multiple animated layers maintain perfect timing alignment and loop synchronously without drift.

## Compatibility & Physics Report
- **GPU Composited Transforms**: Full hardware acceleration using \`translate3d\`, \`rotate\`, \`scale\`.
- **Spring Animations**: ${report.sampledPhysics.length > 0 ? report.sampledPhysics.join(' ') : 'Standard CSS timing functions.'}

## Integration Guide
1. Copy \`animation.css\` and the \`assets/\` folder into your web project.
2. Link the stylesheet in your HTML \`<head>\`:
   \`\`\`html
   <link rel="stylesheet" href="animation.css">
   \`\`\`
3. Embed the stage markup:
   \`\`\`html
${stageHtml}   \`\`\`

Built with Looply — Local-First Visual Animation Studio.
`;

  return {
    css: cssOutput,
    html,
    stageHtml,
    readme,
    report,
  };
}
